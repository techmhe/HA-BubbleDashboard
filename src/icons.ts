/** Pick a tile icon from the device kind and its (display) name. */
export function deviceIcon(id: string, name: string): string {
  const n = `${id} ${name}`.toLowerCase();
  if (id.startsWith('fan.')) return ID.fan;
  if (id.startsWith('humidifier.')) return ID.drop;
  if (id.startsWith('light.')) {
    if (/led|strip|sideboard|stimmung|couch|regal/.test(n)) return ID.strip;
    if (/stehlampe|uhr|wandlampe/.test(n)) return ID.lamp;
    return ID.bulb;
  }
  if (/tv|fernseh|heimkino|kino/.test(n)) return ID.tv;
  if (/brunnen|pumpe/.test(n)) return ID.drop;
  if (/trockner|wasch/.test(n)) return ID.dryer;
  if (/warmwasser|boiler/.test(n)) return ID.boiler;
  if (/deckenlampe|lampe|licht/.test(n)) return ID.bulb;
  return ID.plug;
}
