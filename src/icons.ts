export type IconKey = keyof typeof I;

/** Guess a room icon from its name when the config does not set one. */
export function roomIcon(name: string, explicit?: string): string {
  if (explicit && explicit in I) return I[explicit as IconKey];
  const n = name.toLowerCase();
  if (/büro|arbeits/.test(n)) return I.desk;
  if (/bad|wc/.test(n)) return I.bath;
  if (/schlaf/.test(n)) return I.bed;
  if (/flur|diele|treppe/.test(n)) return I.door;
  if (/wohn/.test(n)) return I.sofa;
  if (/küche|kuche|ess/.test(n)) return I.pot;
  if (/garten|terrasse|balkon/.test(n)) return I.tree;
  return I.home;
}

/** Map a weather entity condition to an icon. */
export function weatherIcon(condition: string): string {
  switch (condition) {
    case 'sunny':
      return I.sun;
    case 'clear-night':
      return I.moon;
    case 'rainy':
    case 'pouring':
      return I.rain;
    case 'lightning':
    case 'lightning-rainy':
    case 'windy':
    case 'windy-variant':
      return I.storm;
    case 'snowy':
    case 'snowy-rainy':
    case 'hail':
      return I.snow;
    case 'fog':
      return I.fog;
    default:
      return I.cloud;
  }
}

